import { chromium, expect } from '@playwright/test'
import { writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
const origin=process.env.AURORA_URL ?? 'http://127.0.0.1:5173'
const api=process.env.AURORA_API_URL ?? 'http://127.0.0.1:8787'
const report=process.env.AURORA_REPORT_DIR ? join(process.env.AURORA_REPORT_DIR, 'interactions.json') : fileURLToPath(new URL('../../../../docs/reports/commons-aurora/interactions.json',import.meta.url))
await mkdir(dirname(report), {recursive:true})
const browser=await chromium.launch()
const checks=[]
try {
  for(const [width,height] of [[1440,900],[390,844]]){
    const context=await browser.newContext({viewport:{width,height}})
    const page=await context.newPage()
    const errors=[]; const fonts=[]
    page.on('pageerror',e=>errors.push(e.message))
    page.on('request',r=>{if(/fonts\.googleapis|fonts\.gstatic/.test(r.url()))fonts.push(r.url())})
    await page.goto(origin)
    await expect(page.getByRole('heading',{name:'Guten Tag, Achim.'})).toBeVisible()
    if(width===390)await expect(page.locator('.panel[data-view="assistant"]')).toBeHidden()
    await page.getByRole('button',{name:'Alle Werkzeuge',exact:true}).click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await expect(page.getByLabel('Werkzeuge suchen')).toBeFocused()
    await page.getByLabel('Werkzeuge suchen').fill('PDF')
    await expect(page.locator('.ov-item')).toHaveCount(1)
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByRole('button',{name:'Alle Werkzeuge',exact:true})).toBeFocused()
    await page.keyboard.press('ControlOrMeta+k')
    await expect(page.getByRole('dialog')).toBeVisible()
    await page.keyboard.press('Shift+Tab')
    await expect(page.getByRole('button',{name:'Favorit hinzufügen'})).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(page.getByLabel('Werkzeuge suchen')).toBeFocused()
    await page.keyboard.press('Escape')
    checks.push({width,check:'Launcher search, Escape, shortcut, focus return and focus trap',passed:true})
    await page.getByRole('link',{name:'Prüfungen',exact:true}).click()
    await expect(page).toHaveURL(/\/actions\/?$/)
    await expect(page.getByRole('link',{name:'Prüfungen',exact:true})).toHaveClass(/on/)
    await page.getByRole('button',{name:'Im Canvas öffnen'}).click()
    await expect(page).toHaveURL(/\/canvas\/schwamm-zitat$/)
    await expect(page.locator('.card')).toHaveCount(5)
    await page.getByRole('link',{name:'Interview von 2019',exact:true}).click()
    await expect(page.locator('#c-origin')).toHaveClass(/hl/)
    await page.getByRole('link',{name:'Weitergabekette',exact:true}).click()
    await expect(page.locator('#c-graph')).toHaveClass(/hl/)
    await expect(page.locator('#c-origin')).not.toHaveClass(/hl/)
    await expect(page.locator('#c-graph')).toBeInViewport()
    await page.getByRole('link',{name:'Assistent',exact:true}).click()
    await page.getByLabel('Frage an den Assistenten').fill('Woher stammt dieses Zitat?')
    await page.getByRole('button',{name:'Frage senden'}).click()
    await expect(page).toHaveURL(/\/canvas\/schwamm-zitat\?query=/)
    await expect(page.locator('.msg').first()).toContainText('Woher stammt dieses Zitat?')
    await page.reload()
    await expect(page.getByRole('link',{name:'Canvas',exact:true})).toHaveClass(/on/)
    await expect(page.locator('.card')).toHaveCount(5)
    checks.push({width,check:'Route modes, review → same canvas → assistant composer, reload, reference highlight/scroll',passed:true})
    for(const path of ['/','/canvas/schwamm-zitat','/actions','/actions/zuschreibung-14']){
      await page.goto(origin+path)
      await page.locator('main').waitFor()
      const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)
      expect(overflow).toBe(false)
    }
    await page.emulateMedia({reducedMotion:'reduce'})
    expect(await page.locator('.btn').first().evaluate(el=>getComputedStyle(el).transitionDuration)).toBe('0s')
    expect(errors).toEqual([]);expect(fonts).toEqual([])
    checks.push({width,check:'Direct routes, no horizontal page overflow, reduced motion, no JS errors, local fonts',passed:true})
    await page.goto(`${origin}/actions/korrektur-rheinlicht`)
    await expect(page.getByRole('heading',{name:'Korrektur nicht übernommen'})).toBeVisible()
    await page.getByRole('link',{name:'Assistent',exact:true}).click()
    await page.getByLabel('Frage an den Assistenten').fill('Welche Korrektur fehlt?')
    await page.getByRole('button',{name:'Frage senden'}).click()
    await expect(page).toHaveURL(/\/canvas\/rheinlicht\?query=/)
    await expect(page.locator('.card')).toHaveCount(0)
    checks.push({width,check:'Another selected review carries its own investigation into the composer; no invented evidence',passed:true})

    await context.close()
  }
  // Establish the repository's existing prototype session only in this disposable browser.
  const participants=await fetch(`${api}/api/participants`).then(r=>r.json())
  const session=await fetch(`${api}/api/auth/session`,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({participantId:participants.participants[0].id})}).then(r=>r.json())
  const context=await browser.newContext({viewport:{width:1440,height:900}})
  await context.addInitScript(s=>localStorage.setItem('br-ai-nstorm.session',JSON.stringify(s)),session)
  const page=await context.newPage()
  await page.goto(`${origin}/find`)
  await page.getByLabel('Quellen finden').fill('My Mac cannot see my frame')
  const searchResponse=page.waitForResponse(r=>r.url().includes('/api/commons/search?')&&r.status()===200)
  await page.getByRole('button',{name:'Finden',exact:true}).last().click()
  await searchResponse
  await expect(page.getByText('Quellen und Beiträge aus dem Commons-Dienst')).toBeVisible()
  const originalTitles=await page.locator('.find-results h2').allTextContents()
  expect(originalTitles.length).toBeGreaterThan(1)
  await page.locator('.find-results .card').nth(0).getByRole('button',{name:'Vergleichen'}).click()
  await page.locator('.find-results .card').nth(1).getByRole('button',{name:'Vergleichen'}).click()
  await expect(page.locator('.comparison')).toBeVisible()
  await page.reload()
  await expect(page.locator('.comparison')).toBeVisible()
  await page.locator('.find-results h2 a').first().click()
  await expect(page.locator('.record')).toBeVisible()
  await expect(page.locator('.record').getByRole('link',{name:'Originalquelle öffnen ↗'}).first()).toHaveAttribute('href',/^https:\/\/github.com\//)
  await page.getByRole('link',{name:'← Zurück zu den Ergebnissen'}).click()
  await expect(page.getByLabel('Quellen finden')).toHaveValue('My Mac cannot see my frame')
  await expect(page.locator('.comparison')).toBeVisible()
  checks.push({check:'Real API search/inspect, source links, unchanged compare module, URL selection and back context',passed:true})
  await page.goto(`${origin}/#/search?q=frame`)
  await expect(page).toHaveURL(/\/find\?query=frame/)
  await expect(page.locator('.find-results h2').first()).toBeVisible()
  checks.push({check:'Existing hash search links redirect into the TanStack read routes',passed:true})
  await page.goto(`${origin}/find?query=My%20Mac%20cannot%20see%20my%20frame`)
  await page.route('**/api/commons/**',route=>route.abort())
  await page.reload()
  await expect(page.getByText('Lokaler Quellenstand · Dienst nicht verbunden')).toBeVisible()
  await expect(page.locator('.find-results h2')).toHaveCount(originalTitles.length)
  checks.push({check:'Service outage uses the real committed corpus fallback',passed:true})
  await context.close()
} catch(error) {
  checks.push({check:'Failure',passed:false,error:String(error)})
  process.exitCode=1
} finally {
  await browser.close()
  await writeFile(report,JSON.stringify(checks,null,2)+'\n')
  console.log(JSON.stringify(checks,null,2))
}
