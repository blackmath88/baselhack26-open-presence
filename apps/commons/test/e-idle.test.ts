import { afterEach, describe, expect, it, vi } from 'vitest'
import { E_IDLE_CYCLE_MS, startIdleCycle } from '../src/companion/idle'
afterEach(() => vi.useRealTimers())
describe('e idle personality cycle', () => {
  it('double blinks, coughs briefly, then slowly exhales and returns to rest', () => {
    vi.useFakeTimers()
    const emit = vi.fn()
    const stop = startIdleCycle(emit)
    vi.advanceTimersByTime(1800)
    expect(emit).toHaveBeenLastCalledWith('blink')
    vi.advanceTimersByTime(160)
    expect(emit).toHaveBeenLastCalledWith('idle')
    vi.advanceTimersByTime(190)
    expect(emit).toHaveBeenLastCalledWith('blink')
    vi.advanceTimersByTime(5450)
    expect(emit).toHaveBeenLastCalledWith('cough')
    vi.advanceTimersByTime(850)
    expect(emit).toHaveBeenLastCalledWith('idle')
    vi.advanceTimersByTime(2550)
    expect(emit).toHaveBeenLastCalledWith('exhale')
    vi.advanceTimersByTime(5199)
    expect(emit).toHaveBeenLastCalledWith('exhale')
    vi.advanceTimersByTime(1)
    expect(emit).toHaveBeenLastCalledWith('idle')
    stop()
    expect(vi.getTimerCount()).toBe(0)
  })
  it('cancels pending cues on pause/unmount and skips starts while inactive', () => {
    vi.useFakeTimers()
    const emit = vi.fn()
    const stop = startIdleCycle(emit, () => false)
    vi.advanceTimersByTime(1800)
    expect(emit).not.toHaveBeenCalled()
    stop()
    vi.advanceTimersByTime(E_IDLE_CYCLE_MS * 3)
    expect(emit).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(0)
  })
  it('repeats without accumulating timers or requiring frame-by-frame updates', () => {
    vi.useFakeTimers()
    const emit = vi.fn()
    const stop = startIdleCycle(emit)
    vi.advanceTimersByTime(E_IDLE_CYCLE_MS * 3 + 1800)
    expect(emit).toHaveBeenLastCalledWith('blink')
    expect(emit.mock.calls.length).toBeLessThan(40)
    expect(vi.getTimerCount()).toBeLessThanOrEqual(11)
    stop()
  })
})
