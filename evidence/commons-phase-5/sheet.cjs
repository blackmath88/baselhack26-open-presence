const { chromium } = require('playwright'); const fs = require('fs')
const [, , file, out] = process.argv
const R = []; const ok = (n, p, d = '') => R.push(`${p ? 'ok  ' : 'FAIL'} ${n}${d ? ' — ' + d : ''}`)
;(async () => {
  const b = await chromium.launch({ executablePath: '/usr/bin/chromium' })
  for (const [vp, w, h, scheme] of [['wide-dark', 1280, 900, 'dark'], ['narrow-light', 390, 844, 'light']]) {
    const ctx = await b.newContext({ viewport: { width: w, height: h }, colorScheme: scheme, acceptDownloads: true }); const p = await ctx.newPage()
    const errs = []; p.on('pageerror', (e) => errs.push(e.message))
    await p.goto('file://' + file)
    await p.fill('#code', 'Anna'); ok(`${vp}: a name triggers the warning`, await p.isVisible('#code-warn'))
    let downloaded = false; p.once('download', () => { downloaded = true }); await p.click('#export-json'); await p.waitForTimeout(500)
    ok(`${vp}: export refuses a name`, !downloaded)
    await p.fill('#code', 'P2'); ok(`${vp}: even code puts GitHub first`, /GitHub first/.test(await p.innerText('#order-line')) && (await p.$$eval('#tasks h2', (h) => h[0].innerText)).includes('GitHub'))
    await p.fill('#code', 'P3'); ok(`${vp}: odd code puts the Commons first`, /Commons first/.test(await p.innerText('#order-line')))
    await p.check('input[name="st-C1"][value="done"]'); await p.fill('fieldset[data-task="C1"] textarea[data-f="notes"]', 'typed "mac usb frame"; read Why it matched')
    await p.click('button[data-timer="C1"]'); await p.waitForTimeout(1300); await p.click('button[data-timer="C1"]')
    ok(`${vp}: timer records seconds`, (await p.innerText('#tm-C1')) !== '0:00', await p.innerText('#tm-C1'))
    await p.focus('fieldset[data-task="C7"] textarea[data-f="quote"]'); await p.keyboard.press('Alt+h'); await p.keyboard.type('stopped at Destination box')
    ok(`${vp}: Alt+H logs a hesitation against the current task`, /C7/.test(await p.innerText('#hes')))
    await p.check('input[name="ac-voices"][value="partly"]')
    await p.reload(); await p.waitForTimeout(200)
    ok(`${vp}: everything survives reload`, (await p.inputValue('#code')) === 'P3' && await p.isChecked('input[name="st-C1"][value="done"]') && (await p.inputValue('[data-hes="0"]')) === 'stopped at Destination box' && await p.isChecked('input[name="ac-voices"][value="partly"]'))
    const [dj] = await Promise.all([p.waitForEvent('download'), p.click('#export-json')]); const j = JSON.parse(fs.readFileSync(await dj.path(), 'utf8'))
    ok(`${vp}: JSON export holds code, task, hesitation and acceptance`, dj.suggestedFilename().startsWith('commons-phase5-P3-') && j.tasks.C1.status === 'done' && j.hesitations[0].task === 'C7' && j.accept.voices.value === 'partly')
    const [dm] = await Promise.all([p.waitForEvent('download'), p.click('#export-md')]); const m = fs.readFileSync(await dm.path(), 'utf8')
    ok(`${vp}: Markdown export has the task table and hesitations`, /\| C1 Find \| done \|/.test(m) && /C7 · stopped at Destination box/.test(m))
    ok(`${vp}: no horizontal scroll`, (await p.evaluate(() => document.documentElement.scrollWidth)) <= w)
    await p.screenshot({ path: `${out}/sheet-${vp}.png` })
    p.on('dialog', (d) => d.accept()); await p.click('#clear'); await p.waitForTimeout(400)
    ok(`${vp}: clear empties the sheet`, (await p.inputValue('#code')) === '')
    ok(`${vp}: no page errors`, errs.length === 0, errs.join('|'))
    await ctx.close()
  }
  console.log(R.join('\n')); await b.close()
})().catch((e) => { console.error(e); console.log(R.join('\n')); process.exit(1) })
